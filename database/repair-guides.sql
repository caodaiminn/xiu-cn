CREATE TABLE IF NOT EXISTS xiu_repair_guides (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 category_id INT UNSIGNED NOT NULL,
 slot TINYINT UNSIGNED NOT NULL,
 slug VARCHAR(120) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 title VARCHAR(120) NOT NULL,
 summary VARCHAR(500) NOT NULL,
 sections MEDIUMTEXT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (category_id) REFERENCES xiu_categories(id) ON DELETE RESTRICT,
 UNIQUE KEY guide_category_slot (category_id,slot)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS xiu_repair_guide_categories (
 category_id INT UNSIGNED NOT NULL,
 slot TINYINT UNSIGNED NOT NULL,
 guide_id INT UNSIGNED NOT NULL,
 PRIMARY KEY (category_id,slot),
 FOREIGN KEY (category_id) REFERENCES xiu_categories(id) ON DELETE CASCADE,
 FOREIGN KEY (guide_id) REFERENCES xiu_repair_guides(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
