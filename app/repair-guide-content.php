function repairGuideProfileKey(array $category,array $catalog): string {
    $name=$category['name'];$root=$category;
    while(!empty($root['parent_id'])) $root=$catalog[(int)$root['parent_id']];
    if(preg_match('/空调|暖通/',$name)) return 'air';
    if(str_contains($name,'工业冷水机')) return 'machine';
    if(preg_match('/冰箱|冷柜|制冰/',$name)) return 'fridge';
    if(str_contains($name,'洗衣')) return 'washer';
    if(str_contains($name,'热水器')) return 'heater';
    if(str_contains($name,'加固')) return 'structure';
    if(str_contains($name,'防水') && (int)$category['id']!==9) return 'waterproof';
    if(preg_match('/消防|电梯/',$name)) return 'firelift';
    if(preg_match('/开锁|换锁|指纹锁|保险柜|智能门锁/',$name)) return 'lock';
    if(preg_match('/门窗|防盗门|卷帘门|感应门|旋转门/',$name)) return 'door';
    if(preg_match('/水管|给排水|管道|下水|马桶疏通|水龙头|化粪池|污水池|管网/',$name)) return 'pipe';
    if(preg_match('/强弱电|水电|电缆|电路|灯具/',$name)) return 'electric';
    if(preg_match('/墙面|地面维修|吊顶|刮胶|瓷砖|石材|地板|翻新.*装修|围墙|小区道路|打孔|切割墙体/',$name)) return 'finish';
    if(preg_match('/网络维护/',$name)) return 'network';
    if(preg_match('/充电|漏电|跳闸/',$name) || (int)$root['id']===129) return 'charge';
    if(preg_match('/变频器|控制器/',$name)) return 'control';
    if(preg_match('/清洗|保洁|清洁/',$name)) return 'clean';
    if(str_contains($name,'搬家')) return 'move';
    if(preg_match('/陪|养老|助浴|助洁|紧急上门/',$name) || (int)$root['id']===165) return 'care';
    if((int)$root['id']===155) return 'adapt';
    if((int)$root['id']===143) return 'smart';
    if(preg_match('/沙发|家具|晾衣架|健身|跑步机/',$name)) return 'furniture';
    if(preg_match('/手表|眼镜|瓷器/',$name)) return 'small';
    $rootProfiles=[1=>'appliance',9=>'building',14=>'digital',18=>'small',23=>'machine',27=>'office',31=>'vehicle',35=>'control',109=>'appliance',118=>'machine',129=>'charge',143=>'smart',155=>'adapt',165=>'care'];
    if(!isset($rootProfiles[(int)$root['id']])) throw new RuntimeException('Missing guide profile for '.$category['name']);
    return $rootProfiles[(int)$root['id']];
}

