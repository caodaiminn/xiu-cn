function buildRepairGuideContent(array $category,array $catalog): array {
    $profiles=repairGuideProfiles();$profile=$profiles[repairGuideProfileKey($category,$catalog)];
    $focus=repairGuideFocus($category);$name=$category['name'];
    $children=array_values(array_filter($catalog,fn($item)=>(int)$item['parent_id']===(int)$category['id']));
    if($children) $focus[]='该分类包含：'.implode('、',array_column($children,'name')).'。预约时选择具体项目，明确本次需要处理的对象。';
    if(in_array($name,['陪练车','陪驾公司'],true)) {
        $profile['risk']='驾驶与训练须符合驾驶资格、车辆使用和道路交通要求；天气、身体状态或道路条件不适合时调整安排，不在交通危险环境中训练。';
        $profile['prepare']=['驾驶资格、车辆授权与保险情况','路线、训练目标、车辆状态与交接地点','服务时长、陪同人员及紧急联络安排'];
        $profile['accept']=['核对约定路线或训练项目与服务时长','记录车辆状态、费用及需要继续练习的事项','确认车辆、钥匙与资料交接'];
    }
    $topics=[
        1=>['wen-ti-ji-lu','常见问题与现场记录','先把问题发生条件、影响范围和现场表现记录清楚，便于区分检测、维修与其他服务需求。'],
        2=>['bao-xiu-zhun-bei','报修预约与资料准备','整理对象资料、现场照片、进场条件和预约要求，减少服务方反复询问。'],
        3=>['bao-jia-he-dui','报价项目与费用核对','拆分检测、人工、材料、附加项目和售后范围，明确变更费用的确认方式。'],
        4=>['wan-gong-yan-shou','完工验收与交接清单','按原问题和约定项目检查效果，记录测试条件、用料和需要继续观察的事项。'],
        5=>['ri-chang-wei-hu','日常维护与再次报修','整理适合该分类的维护要点与异常记录，保留资料，避免小问题被忽略。'],
    ];
    $output=[];
    foreach($topics as $slot=>[$slug,$topic,$intro]) {
        $sections=[['heading'=>'适用范围与分类重点','paragraphs'=>['本篇供'.$category['label'].'的服务预约、沟通和验收参考；它不是商家广告或真实求修委托。具体型号、材料和现场条件不同，处理办法应以说明书、双方约定及现场专业判断为准。'],'items'=>$focus]];
        if($slot===1) {
            $sections[]=['heading'=>'先记录哪些现象','items'=>$profile['observe']];
            $sections[]=['heading'=>'怎样留下可用的记录','paragraphs'=>['记录第一次出现问题的时间、能否重复、影响哪个部位，以及最近是否做过搬动、改造或维护。照片先拍整体位置，再拍问题细节；附上能辨认型号或材料的信息。','不要把猜测写成已确定的故障原因。同一地点有多个问题时分别描述，便于服务方评估检测范围。']];
            $sections[]=['heading'=>'下一步准备','items'=>array_slice($profile['prepare'],0,2)];
        } elseif($slot===2) {
            $sections[]=['heading'=>'预约前的资料清单','items'=>$profile['prepare']];
            $sections[]=['heading'=>'确认现场与时间','paragraphs'=>['告诉服务方所在城市、具体区域及可联系时间。需要上门时确认楼层、电梯、停车、进场预约和现场负责人；涉及公共部位或邻接空间，应先沟通物业或相关人员。','预约前问清是否提供该分类服务、能否到达该地址、预计检查时间和未完成维修时的计费方式。在线资料不能代替到场后的检测结论。']];
            $sections[]=['heading'=>'报修说明示例','paragraphs'=>['需要处理'.$name.'相关问题。对象或型号：____；具体部位与现象：____；首次出现时间：____；此前处理：____；地址与现场条件：____；希望完成的项目：____；可预约时间：____。请先确认检测范围与费用，再安排处理。']];
        } elseif($slot===3) {
            $sections[]=['heading'=>'逐项核对报价','items'=>$profile['quote']];
            $sections[]=['heading'=>'处理追加项目','paragraphs'=>['书面记录项目名称、数量或计费单位、单价和是否包含材料。总价或区间报价都应说明适用条件；未检测时的估价不能当作最终结算价。','现场发现新增问题时，让服务方先解释原因、处理范围与新增费用。确认后再施工；若不接受，说明停止位置、已发生费用和恢复现场的安排。']];
            $sections[]=['heading'=>'售后和凭据','paragraphs'=>['确认质保对象、期限、复发检查的办法及不覆盖的情况。结算凭据应能对应本次项目；保留检测记录、材料或配件信息和双方确认的变更。']];
        } elseif($slot===4) {
            $sections[]=['heading'=>'本分类的验收重点','items'=>$profile['accept']];
            $sections[]=['heading'=>'用原问题复核效果','paragraphs'=>['把原来的问题、约定完成项和实际交付一一对照。需要运行、观察或等待养护时，约定测试条件和复查时间，不以短暂试用代替后续检查。','有拆装、隐蔽或恢复饰面项目时，核对施工照片、现场保护和清运。发现差异应当场记录，与服务方确认处理期限及再次检查方式。']];
            $sections[]=['heading'=>'交接清单','items'=>['约定项目、检测或测试结果与尚未处理的问题','材料、配件及更换件的规格，设备参数或相关配置','养护与使用说明、维修凭据、质保边界及联系办法']];
        } else {
            $sections[]=['heading'=>'日常使用与维护','items'=>$profile['care']];
            $sections[]=['heading'=>'建立维护记录','paragraphs'=>['把对象型号、位置、上次服务内容和交付日期放在同一份记录里。按照说明书、设计方案或服务方书面交接安排维护，不为所有设备套用相同的周期。','问题再次出现时，补充时间、使用条件和变化照片，联系原服务方说明是否在约定保障范围。不要只写“又坏了”，也不要反复尝试可能加重问题的操作。']];
            $sections[]=['heading'=>'再次预约应补充的信息','items'=>['上次处理范围、配件或材料与保修凭据','与上次相比的新现象、发生频次及影响范围','现场和使用条件的变化，以及希望安排的复查项目']];
        }
        $sections[]=['heading'=>'涉及安全的情况','paragraphs'=>[$profile['risk']]];
        $output[]=['slot'=>$slot,'slug'=>'g'.$category['id'].'-'.$slug,'title'=>$name.'：'.$topic,'summary'=>$name.'指南。'.$intro.'重点包括：'.$profile[['observe','prepare','quote','accept','care'][$slot-1]][0].'。','sections'=>$sections];
    }
    return $output;
}
